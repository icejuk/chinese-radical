/* โครงข้อมูลของแอป — "ราก" (部首/偏旁) และ "ตัวอักษร" ที่ประกอบจากราก
   หลักคิด: ตัวอักษรจีนส่วนใหญ่ = ราก 2–3 ตัวมาต่อกัน
   รู้ราก 100 ตัว → เดาความหมายของตัวที่ไม่เคยเห็นได้ (เดา "เสียง" ไม่ได้ ต้องมีพินอินกำกับเสมอ) */

/** หมวดของราก — จัดตามความหมาย ไม่ใช่ตามจำนวนขีด เพราะจำเป็นกลุ่มเรื่องง่ายกว่า */
export const RAD_CATS = [
  'คน',
  'ร่างกาย',
  'มือ-เท้า',
  'ใจ-ความคิด',
  'ปาก-พูด',
  'ธรรมชาติ',
  'พืช-ต้นไม้',
  'สัตว์',
  'อาคาร-ที่อยู่',
  'สิ่งของ-เครื่องมือ',
  'เงิน-ค้าขาย',
  'เส้น-ผ้า',
  'อาหาร',
  'เดินทาง',
  'อื่นๆ',
] as const
export type RadCat = (typeof RAD_CATS)[number]

/** ตำแหน่งที่รากมักไปอยู่ในตัวอักษร — ใช้จัดเลย์เอาต์แผนภาพแตกตัวอักษร */
export type RadPos = 'left' | 'right' | 'top' | 'bottom' | 'enclose' | 'any'

/** rad = รากที่บอกความหมาย · sound = ส่วนที่ปกติทำหน้าที่บอกเสียง (声旁) เช่น 可 ใน 河
    แยกไว้เพื่อให้หน้าเรียนโชว์เฉพาะ rad (100 ตัว) ส่วน sound โผล่ตอนแตกตัวอักษรเท่านั้น */
export type RadKind = 'rad' | 'sound'

export type Radical = {
  /** ตัวรากในรูปมาตรฐาน (ที่ใช้เป็นคีย์อ้างอิงใน Hanzi.parts) */
  r: string
  kind: RadKind
  /** รูปแปรเมื่อไปอยู่ในตัวอักษร เช่น 水 → 氵 · 手 → 扌 */
  vars?: string[]
  py: string
  /** ความหมายไทยสั้นๆ (คำเดียว/วลีสั้น) */
  th: string
  en: string
  strokes: number
  cat: RadCat
  pos: RadPos
  /** เรื่องเล่าช่วยจำภาษาไทย — ที่มาของรูป → ความหมาย (นี่คือหัวใจของแอป ห้ามว่าง) */
  story: string
}

export type Hanzi = {
  /** ตัวอักษรเดี่ยว 1 ตัว */
  zh: string
  py: string
  /** ความหมายไทย */
  th: string
  /** ราก/ส่วนประกอบที่แตกออกมา เรียงตามลำดับการอ่าน (ซ้าย→ขวา, บน→ล่าง)
      ค่าต้องตรงกับ Radical.r หรือ Radical.vars ตัวใดตัวหนึ่ง — มีเทสคุมไว้ */
  parts: string[]
  /** ไทย: รากพวกนี้รวมกันได้ความหมายนี้ยังไง (ห้ามว่าง) */
  hint: string
  /** ส่วนที่ทำหน้าที่บอกเสียง (声旁) ถ้ามี — ช่วยอธิบายว่าทำไมอ่านแบบนี้ */
  sound?: string
  hsk?: 1 | 2 | 3
  /** คำที่ตัวนี้ไปโผล่บ่อย — ให้เห็นว่าเรียนไปใช้ตรงไหน */
  words?: { zh: string; py: string; th: string }[]
}

/** โครงตัวอักษร — บอกว่ารากวางตัวกันแบบไหน ใช้เลือกเลย์เอาต์แผนภาพ */
export type Layout = 'lr' | 'tb' | 'enclose' | 'single'
