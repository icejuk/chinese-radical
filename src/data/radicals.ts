/** หา Radical จากอักขระ — รับทั้งรูปมาตรฐานและรูปแปร (氵 → 水) */
export function findRad(ch: string): Radical | undefined {
  return radicals.find((r) => r.r === ch || r.vars?.includes(ch))
}

/** รากที่ต้องเรียน (ไม่รวมส่วนบอกเสียง) */
export const learnRadicals = () => radicals.filter((r) => r.kind === 'rad')
